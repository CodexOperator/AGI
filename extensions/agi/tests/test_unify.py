# --- idempotency: a clean refusal on a second run -------------------------------


def test_second_run_refuses_cleanly(migrated):
    """unify.py picks "refuse", not "re-apply", for a second run (see the
    module docstring): preflight requires no `.agi/` in the target, which the
    first successful run created."""
    engine, tree = migrated["engine"], migrated["tree"]
    assert migrated["report"]["ok"] is True

    second = unify.run_unify(engine, tree, yes=True)
    assert second["ok"] is False
    assert second["reason"] == "engine_has_agi_already"

    # and it changed nothing further
    assert unify.count_grid_refs(engine) == 2


