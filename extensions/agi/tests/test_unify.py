# --- dry run mutates nothing ---------------------------------------------------


def test_dry_run_mutates_nothing(repos):
    engine, tree = repos
    head_before = _rev_parse(engine)
    refs_before = _git(engine, "show-ref")

    report = unify.run_unify(engine, tree, yes=False)

    assert report["ok"] is True
    assert report["dry_run"] is True
    assert _rev_parse(engine) == head_before
    assert _git(engine, "show-ref") == refs_before
    assert not (engine / ".agi").exists()
    assert "agi-unify-source" not in _git(engine, "remote")


def test_explicit_dry_run_flag_overrides_yes(repos):
    """main()'s --dry-run forces a plan even when --yes is also passed."""
    engine, tree = repos
    head_before = _rev_parse(engine)
    rc = unify.main(["--engine", str(engine), "--tree", str(tree), "--yes", "--dry-run"])
    assert rc == 0
    assert _rev_parse(engine) == head_before
    assert not (engine / ".agi").exists()


